import '../../core/theme/app_tokens.dart';
import 'package:flutter/material.dart';

import '../../models/inventory_item.dart';

class ResultCards extends StatelessWidget {
  final List<Map<String, String>> results;
  final List<InventoryItem> inventoryItems;
  final bool isRecipeResult;
  final Future<void> Function(List<InventoryItem>)? onCookRecipe;

  const ResultCards({
    super.key,
    required this.results,
    required this.inventoryItems,
    required this.isRecipeResult,
    this.onCookRecipe,
  });

  @override
  Widget build(BuildContext context) {
    if (results.isEmpty) {
      return const _EmptyResultCard();
    }

    return Column(
      children: results.map((result) {
        final title = _cleanTitle(result['title'] ?? 'AI Suggestion');
        final content = result['content'] ?? '';

        return _ResultCard(
          title: title,
          content: content,
          isRecipeResult: isRecipeResult,
        );
      }).toList(),
    );
  }

  String _cleanTitle(String value) {
    return value
        .replaceAll(RegExp(r'^Recipe\s*\d+\s*:\s*', caseSensitive: false), '')
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .replaceAll('Generated by Groq AI', '')
        .replaceAll(
          RegExp(r'Generated by [a-z0-9_-]+(?: AI)?', caseSensitive: false),
          '',
        )
        .trim();
  }
}

class _ResultCard extends StatelessWidget {
  final String title;
  final String content;
  final bool isRecipeResult;

  const _ResultCard({
    required this.title,
    required this.content,
    required this.isRecipeResult,
  });

  @override
  Widget build(BuildContext context) {
    final icon = isRecipeResult
        ? Icons.restaurant_menu_rounded
        : Icons.inventory_2_rounded;

    final label = isRecipeResult ? 'Cafe Recipe' : 'Restock Advice';

    return Container(
      width: double.infinity,
      margin: const EdgeInsets.only(bottom: 14),
      padding: const EdgeInsets.all(18),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(18),
        border: Border.all(color: AppColors.border),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.04),
            blurRadius: 16,
            offset: const Offset(0, 7),
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                height: 44,
                width: 44,
                decoration: BoxDecoration(
                  color: AppColors.nude,
                  borderRadius: BorderRadius.circular(16),
                ),
                child: Icon(icon, color: AppColors.primary),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Text(
                  title,
                  style: const TextStyle(
                    color: AppColors.textPrimary,
                    fontSize: 16,
                    fontWeight: FontWeight.w600,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: BoxDecoration(
              color: AppColors.nude,
              borderRadius: BorderRadius.circular(999),
            ),
            child: Text(
              label,
              style: const TextStyle(
                color: AppColors.primary,
                fontSize: 11,
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
          const SizedBox(height: 12),
          Text(
            content,
            style: const TextStyle(
              color: AppColors.textPrimary,
              fontSize: 13,
              height: 1.45,
              fontWeight: FontWeight.w600,
            ),
          ),
        ],
      ),
    );
  }
}

class _EmptyResultCard extends StatelessWidget {
  const _EmptyResultCard();

  @override
  Widget build(BuildContext context) {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(18),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(18),
        border: Border.all(color: AppColors.border),
      ),
      child: const Text(
        'No result found.',
        style: TextStyle(
          color: AppColors.textSecondary,
          fontWeight: FontWeight.w700,
        ),
      ),
    );
  }
}
