part of 'recipe_detail_page.dart';

abstract class _RecipeDetailBase extends State<RecipeDetailPage> {
  CookNowDeductionService? _deductionService;

  bool _isCooking = false;

  String get _cleanTitle {
    return widget.title
        .replaceAll(RegExp(r'^Recipe\s*\d+\s*:\s*', caseSensitive: false), '')
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .replaceAll('Generated by Groq AI', '')
        .replaceAll(
          RegExp(r'Generated by [a-z0-9_-]+(?: AI)?', caseSensitive: false),
          '',
        )
        .trim();
  }

  List<String> get _inventoryIngredients {
    return widget.ingredients
        .where((item) => !_isMissingIngredient(item))
        .map(_cleanListItem)
        .where((item) => item.isNotEmpty)
        .toList();
  }

  List<String> get _missingIngredients {
    return widget.ingredients
        .where(_isMissingIngredient)
        .map((item) {
          return item
              .replaceAll(
                RegExp(r'missing\s*/?\s*restock\s*:', caseSensitive: false),
                '',
              )
              .replaceAll(RegExp(r'missing\s*:', caseSensitive: false), '')
              .replaceAll(RegExp(r'restock\s*:', caseSensitive: false), '')
              .trim();
        })
        .map(_cleanListItem)
        .where((item) => item.isNotEmpty)
        .toList();
  }

  List<String> get _cleanSteps {
    final cleaned = widget.steps
        .map(_cleanStep)
        .where((step) => step.isNotEmpty)
        .toList();

    if (cleaned.isEmpty) {
      return [
        'Prepare all available cafe ingredients before cooking.',
        'Follow the recipe method carefully using safe food handling.',
        'Serve the dish fresh and update inventory using Cook Now.',
      ];
    }

    return cleaned;
  }

  bool _isMissingIngredient(String value) {
    final lower = value.toLowerCase();

    return lower.contains('missing') || lower.contains('restock');
  }

  bool _isNearExpiry(String ingredient) {
    return widget.nearExpiryIngredients.any(
      (item) => item.toLowerCase().trim() == ingredient.toLowerCase().trim(),
    );
  }

  String _cleanListItem(String value) {
    return value
        .replaceAll(RegExp(r'^[-•]\s*'), '')
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .trim();
  }

  String _cleanStep(String value) {
    return value
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .replaceAll(RegExp(r'^[-•]\s*'), '')
        .trim();
  }

  Future<void> _handleCookNow() async {
    if (_isCooking) return;

    final portions = await _showPortionDialog();

    if (portions == null || portions <= 0) return;

    setState(() => _isCooking = true);

    try {
      User? user = FirebaseAuth.instance.currentUser;

      user ??= await FirebaseAuth.instance
          .authStateChanges()
          .firstWhere((authUser) => authUser != null, orElse: () => null)
          .timeout(const Duration(seconds: 3), onTimeout: () => null);

      if (!mounted) return;

      if (user == null) {
        setState(() => _isCooking = false);

        _showSnackBar(
          message:
              'Login session not detected. Please reopen app and login again.',
          isError: true,
        );
        return;
      }

      final result = await (_deductionService ??= CookNowDeductionService())
          .deductRecipeIngredients(
            userId: user.uid,
            recipeTitle: _cleanTitle,
            ingredients: _inventoryIngredients,
            portions: portions,
          )
          .timeout(
            const Duration(seconds: 10),
            onTimeout: () {
              return const CookNowDeductionResult(
                success: false,
                message: 'Inventory update took too long. Please try again.',
                usedItems: [],
                skippedItems: [],
              );
            },
          );

      if (!mounted) return;

      setState(() => _isCooking = false);

      _showResultDialog(result);
    } catch (e) {
      if (!mounted) return;

      setState(() => _isCooking = false);

      _showSnackBar(
        message: 'Failed to use Cook Now. Please try again.',
        isError: true,
      );
    }
  }

  Future<int?> _showPortionDialog();
  void _showSnackBar({required String message, required bool isError});
  void _showResultDialog(CookNowDeductionResult result);
}
