part of 'suggestions_page.dart';

abstract class _SuggestionsGeneration extends _SuggestionsFoundation {
  @override
  Future<void> _generateAiResult({
    required String type,
    required List<InventoryItem> items,
    required Future<String> Function() fetcher,
  }) async {
    setState(() {
      _isLoading = true;
      _isCached = false;
      _inventoryChanged = false;
    });

    final data = await _aiService.generate(
      type: type,
      items: items,
      fetcher: fetcher,
    );

    if (!mounted) return;

    String result = data['result'] ?? '';

    if (data['isError'] == true || _isErrorResult(result)) {
      _handleAiError(result);
      return;
    }

    await _loadQuota();

    final isCachedResult = data['isCached'] ?? false;

    if (type == 'recipes_v2') {
      result = await _filterSkippedFromText(result);
    }

    if (type == 'recipes_v2' && isCachedResult == false) {
      await _saveGeneratedRecipes(result, items);
    }

    if (!mounted) return;

    setState(() {
      _resultText = result;
      _resultSignature = data['signature'] ?? '';
      _isCached = isCachedResult;
      _isLoading = false;
      _aiStatus = isCachedResult ? 'Using cache' : 'Groq Available';
    });
  }

  @override
  Future<String> _filterSkippedFromText(String text) async {
    final cleanedText = _removeAiStatusLines(text);

    if (GroqRecipeFormatter.isEmptyResult(cleanedText)) return cleanedText;

    if (cleanedText.trim().isEmpty) {
      return cleanedText;
    }

    final recipes = _helper.parseRecipes(cleanedText);

    if (recipes.isEmpty) {
      return cleanedText;
    }

    final visibleRecipes = await _skippedService.filterSkippedRecipes(
      recipes: recipes,
      titleGetter: (recipe) => recipe['title'] ?? '',
    );

    if (visibleRecipes.isEmpty) {
      return '''
No recipe suggestions available right now.

All current recipes were skipped before. Tap "Reset Skipped" or generate again to get new ideas.
'''
          .trim();
    }

    return _rebuildRecipeText(visibleRecipes);
  }

  String _removeAiStatusLines(String text) {
    final lines = text.split('\n');

    final cleanedLines = lines.where((line) {
      final lower = line.trim().toLowerCase();

      if (lower.isEmpty) return true;

      if (lower == 'generated by groq ai') return false;
      if (lower == 'generated by groq') return false;
      if (lower == 'velora ai provider: groq') return false;
      if (lower.startsWith('generated by')) return false;
      if (lower.contains('generated by groq ai')) return false;

      return true;
    }).toList();

    return cleanedLines.join('\n').trim();
  }

  String _rebuildRecipeText(List<Map<String, String>> recipes) {
    // Preserve recipe bodies, including missing ingredients and instructions.
    return recipes
        .map((recipe) {
          final title = recipe['title'] ?? 'Recipe';
          final content = recipe['content'] ?? '';
          return '### $title\n\n$content';
        })
        .join('\n\n');
  }

  Future<void> _skipFirstVisibleRecipe() async {
    final cleanedText = _removeAiStatusLines(_resultText);
    final recipes = _helper.parseRecipes(cleanedText);

    if (recipes.isEmpty) {
      _showSnack('No recipe to skip.');
      return;
    }

    final title = recipes.first['title'] ?? 'Recipe';

    await _skippedService.skipRecipe(title);
    await _loadSkippedCount();

    final filtered = await _filterSkippedFromText(cleanedText);

    if (!mounted) return;

    setState(() => _resultText = filtered);

    _showSnack('$title skipped.');
  }

  Future<void> _clearSkippedRecipes() async {
    await _skippedService.clearSkippedRecipes();
    await _loadSkippedCount();

    if (!mounted) return;

    setState(() {});

    _showSnack('Skipped recipes reset.');
  }

  bool _isErrorResult(String text);
  void _handleAiError(String result);
  Future<void> _saveGeneratedRecipes(String result, List<InventoryItem> items);
}
