class RecipeParser {
  static String title(Map<String, String> recipe) {
    final raw =
        recipe['title']?.trim() ?? recipe['name']?.trim() ?? 'Cafe Recipe';

    return _cleanTitle(raw);
  }

  static String content(Map<String, String> recipe) {
    return recipe['content']?.trim() ?? '';
  }

  // Older saved bodies use optional colons, markdown headings and several
  // list styles. Normalize presentation without rewriting stored documents.
  static String _line(String line) => line
      .trim()
      .replaceAll('**', '')
      .replaceAll('__', '')
      .replaceFirst(RegExp(r'^#{1,6}[ \t]*'), '')
      .trim();

  static ({String section, String inline})? _heading(String raw) {
    final match = RegExp(
      r'^(ingredients(?:[ \t]+used)?|missing[ \t]*(?:/[ \t]*restock[ \t]*)?ingredients|steps|instructions|method|directions|why(?:[ \t]+recommended)?)(?:[ \t]*:[ \t]*(.*))?$',
      caseSensitive: false,
    ).firstMatch(_line(raw));
    if (match == null) return null;
    final label = match.group(1)!.toLowerCase();
    return (
      section: label.startsWith('missing')
          ? 'missing'
          : label.startsWith('ingredients')
          ? 'used'
          : label.startsWith('why')
          ? 'why'
          : 'steps',
      inline: match.group(2)?.trim() ?? '',
    );
  }

  static String _listItem(String raw) => _line(raw)
      .replaceFirst(RegExp(r'^(?:[-*\u2022\u2013][ \t]*|\d+[.)][ \t]+)'), '')
      .trim();

  static List<String> ingredients(String content) {
    var section = '';
    final result = <String>[];
    for (final raw in content.split('\n')) {
      final heading = _heading(raw);
      if (heading != null) section = heading.section;
      final item = _listItem(heading?.inline ?? raw);
      if ((section == 'used' || section == 'missing') && item.isNotEmpty) {
        result.add(section == 'missing' ? 'Missing / Restock: $item' : item);
      }
    }
    return result;
  }

  static List<String> steps(String content) {
    var section = '';
    final result = <String>[];
    for (final raw in content.split('\n')) {
      final heading = _heading(raw);
      if (heading != null) section = heading.section;
      final item = _listItem(heading?.inline ?? raw);
      if (section == 'steps' && item.isNotEmpty) result.add(item);
    }
    return result;
  }

  static String why(String content) {
    var section = '';
    final result = <String>[];
    for (final raw in content.split('\n')) {
      final heading = _heading(raw);
      if (heading != null) section = heading.section;
      final line = _line(heading?.inline ?? raw);
      if (section == 'why' && line.isNotEmpty) result.add(line);
    }
    return result.isEmpty
        ? 'This recipe helps use available cafe inventory efficiently.'
        : result.join('\n');
  }

  static List<String> nearExpiryNames(List<dynamic> items) {
    return items.map((e) => e.name.toString()).toList();
  }

  static String _cleanTitle(String value) {
    String cleaned = value.trim();

    cleaned = cleaned.replaceAll(
      RegExp(r'^generated by [a-z0-9_-]+(?: ai)?\s*', caseSensitive: false),
      '',
    );

    cleaned = cleaned.replaceAll(
      RegExp(r'^recipe\s*(?:\d+)?\s*:\s*', caseSensitive: false),
      '',
    );

    cleaned = cleaned.replaceAll(RegExp(r'^\d+\.\s*'), '');

    cleaned = cleaned.replaceAll(RegExp(r'^-\s*'), '');

    cleaned = cleaned.trim();

    if (cleaned.isEmpty) {
      return 'Cafe Recipe';
    }

    return cleaned;
  }
}
