import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/material.dart';

import 'logic_suggestions/cook_now_deduction_service.dart';

class RecipeDetailPage extends StatefulWidget {
  final String title;
  final List<String> ingredients;
  final List<String> steps;
  final List<String> nearExpiryIngredients;
  final String whyRecommended;

  const RecipeDetailPage({
    super.key,
    required this.title,
    required this.ingredients,
    required this.steps,
    required this.nearExpiryIngredients,
    required this.whyRecommended,
  });

  @override
  State<RecipeDetailPage> createState() => _RecipeDetailPageState();
}

class _RecipeDetailPageState extends State<RecipeDetailPage> {
  final CookNowDeductionService _deductionService = CookNowDeductionService();

  bool _isCooking = false;

  String get _cleanTitle {
    return widget.title
        .replaceAll(RegExp(r'^Recipe\s*\d+\s*:\s*', caseSensitive: false), '')
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .replaceAll('Generated by Groq AI', '')
        .replaceAll(
          RegExp(r'Generated by [a-z0-9_-]+(?: AI)?', caseSensitive: false),
          '',
        )
        .trim();
  }

  List<String> get _inventoryIngredients {
    return widget.ingredients
        .where((item) => !_isMissingIngredient(item))
        .map(_cleanListItem)
        .where((item) => item.isNotEmpty)
        .toList();
  }

  List<String> get _missingIngredients {
    return widget.ingredients
        .where(_isMissingIngredient)
        .map((item) {
          return item
              .replaceAll(
                RegExp(r'missing\s*/?\s*restock\s*:', caseSensitive: false),
                '',
              )
              .replaceAll(RegExp(r'missing\s*:', caseSensitive: false), '')
              .replaceAll(RegExp(r'restock\s*:', caseSensitive: false), '')
              .trim();
        })
        .map(_cleanListItem)
        .where((item) => item.isNotEmpty)
        .toList();
  }

  List<String> get _cleanSteps {
    final cleaned = widget.steps
        .map(_cleanStep)
        .where((step) => step.isNotEmpty)
        .toList();

    if (cleaned.isEmpty) {
      return [
        'Prepare all available cafe ingredients before cooking.',
        'Follow the recipe method carefully using safe food handling.',
        'Serve the dish fresh and update inventory using Cook Now.',
      ];
    }

    return cleaned;
  }

  bool _isMissingIngredient(String value) {
    final lower = value.toLowerCase();

    return lower.contains('missing') || lower.contains('restock');
  }

  bool _isNearExpiry(String ingredient) {
    return widget.nearExpiryIngredients.any(
      (item) => item.toLowerCase().trim() == ingredient.toLowerCase().trim(),
    );
  }

  String _cleanListItem(String value) {
    return value
        .replaceAll(RegExp(r'^[-•]\s*'), '')
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .trim();
  }

  String _cleanStep(String value) {
    return value
        .replaceAll(RegExp(r'^\d+\.\s*'), '')
        .replaceAll(RegExp(r'^[-•]\s*'), '')
        .trim();
  }

  Future<void> _handleCookNow() async {
    if (_isCooking) return;

    final portions = await _showPortionDialog();

    if (portions == null || portions <= 0) return;

    setState(() => _isCooking = true);

    try {
      User? user = FirebaseAuth.instance.currentUser;

      user ??= await FirebaseAuth.instance
          .authStateChanges()
          .firstWhere((authUser) => authUser != null, orElse: () => null)
          .timeout(const Duration(seconds: 3), onTimeout: () => null);

      if (!mounted) return;

      if (user == null) {
        setState(() => _isCooking = false);

        _showSnackBar(
          message:
              'Login session not detected. Please reopen app and login again.',
          isError: true,
        );
        return;
      }

      final result = await _deductionService
          .deductRecipeIngredients(
            userId: user.uid,
            recipeTitle: _cleanTitle,
            ingredients: _inventoryIngredients,
            portions: portions,
          )
          .timeout(
            const Duration(seconds: 10),
            onTimeout: () {
              return const CookNowDeductionResult(
                success: false,
                message: 'Inventory update took too long. Please try again.',
                usedItems: [],
                skippedItems: [],
              );
            },
          );

      if (!mounted) return;

      setState(() => _isCooking = false);

      _showResultDialog(result);
    } catch (e) {
      if (!mounted) return;

      setState(() => _isCooking = false);

      _showSnackBar(
        message: 'Failed to use Cook Now. Please try again.',
        isError: true,
      );
    }
  }

  Future<int?> _showPortionDialog() async {
    int portions = 1;

    return showDialog<int>(
      context: context,
      builder: (context) {
        return StatefulBuilder(
          builder: (context, setDialogState) {
            return AlertDialog(
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(24),
              ),
              title: const Text(
                'Cook Now',
                style: TextStyle(fontWeight: FontWeight.w900),
              ),
              content: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  const Text(
                    'How many portions/orders did you cook?',
                    textAlign: TextAlign.center,
                    style: TextStyle(
                      color: Color(0xFF6B7280),
                      fontWeight: FontWeight.w600,
                      height: 1.4,
                    ),
                  ),
                  const SizedBox(height: 18),
                  Container(
                    padding: const EdgeInsets.all(10),
                    decoration: BoxDecoration(
                      color: const Color(0xFFF8FAFC),
                      borderRadius: BorderRadius.circular(18),
                      border: Border.all(color: const Color(0xFFE5E7EB)),
                    ),
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        IconButton(
                          onPressed: portions <= 1
                              ? null
                              : () {
                                  setDialogState(() => portions--);
                                },
                          icon: const Icon(Icons.remove_circle_outline),
                          color: const Color(0xFF7C3AED),
                        ),
                        Container(
                          width: 64,
                          alignment: Alignment.center,
                          child: Text(
                            portions.toString(),
                            style: const TextStyle(
                              fontSize: 28,
                              fontWeight: FontWeight.w900,
                              color: Color(0xFF111827),
                            ),
                          ),
                        ),
                        IconButton(
                          onPressed: portions >= 10
                              ? null
                              : () {
                                  setDialogState(() => portions++);
                                },
                          icon: const Icon(Icons.add_circle_outline),
                          color: const Color(0xFF7C3AED),
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: 10),
                  const Text(
                    'Velora will deduct this amount from each matched inventory ingredient.',
                    textAlign: TextAlign.center,
                    style: TextStyle(
                      color: Color(0xFF9CA3AF),
                      fontSize: 12,
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                ],
              ),
              actions: [
                TextButton(
                  onPressed: () => Navigator.pop(context),
                  child: const Text(
                    'Cancel',
                    style: TextStyle(fontWeight: FontWeight.w900),
                  ),
                ),
                ElevatedButton(
                  onPressed: () => Navigator.pop(context, portions),
                  style: ElevatedButton.styleFrom(
                    backgroundColor: const Color(0xFF7C3AED),
                    foregroundColor: Colors.white,
                    elevation: 0,
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(14),
                    ),
                  ),
                  child: const Text(
                    'Confirm',
                    style: TextStyle(fontWeight: FontWeight.w900),
                  ),
                ),
              ],
            );
          },
        );
      },
    );
  }

  void _showSnackBar({required String message, required bool isError}) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        backgroundColor: isError
            ? const Color(0xFFEF4444)
            : const Color(0xFF10B981),
        content: Text(
          message,
          style: const TextStyle(fontWeight: FontWeight.w700),
        ),
      ),
    );
  }

  void _showResultDialog(CookNowDeductionResult result) {
    showDialog(
      context: context,
      builder: (context) {
        return AlertDialog(
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(24),
          ),
          title: Text(
            result.success ? 'Inventory Updated' : 'Cook Now Failed',
            style: const TextStyle(fontWeight: FontWeight.w900),
          ),
          content: SingleChildScrollView(
            child: Text(
              _buildResultMessage(result),
              style: const TextStyle(
                color: Color(0xFF374151),
                height: 1.45,
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.pop(context);

                if (result.success) {
                  Navigator.pop(context, true);
                }
              },
              child: const Text(
                'OK',
                style: TextStyle(fontWeight: FontWeight.w900),
              ),
            ),
          ],
        );
      },
    );
  }

  String _buildResultMessage(CookNowDeductionResult result) {
    final buffer = StringBuffer();

    buffer.writeln(result.message);

    if (result.usedItems.isNotEmpty) {
      buffer.writeln('');
      buffer.writeln('Used items:');

      for (final item in result.usedItems) {
        buffer.writeln('• $item');
      }
    }

    if (result.skippedItems.isNotEmpty) {
      buffer.writeln('');
      buffer.writeln('Skipped items:');

      for (final item in result.skippedItems) {
        buffer.writeln('• $item');
      }
    }

    return buffer.toString().trim();
  }

  @override
  Widget build(BuildContext context) {
    final isSmall = MediaQuery.of(context).size.width < 370;

    return Scaffold(
      backgroundColor: const Color(0xFFF8FAFC),
      appBar: AppBar(
        backgroundColor: const Color(0xFFF8FAFC),
        elevation: 0,
        iconTheme: const IconThemeData(color: Color(0xFF111827)),
        title: const Text(
          'Recipe Details',
          style: TextStyle(
            color: Color(0xFF111827),
            fontWeight: FontWeight.w900,
          ),
        ),
      ),
      body: ListView(
        padding: EdgeInsets.fromLTRB(
          isSmall ? 16 : 20,
          8,
          isSmall ? 16 : 20,
          110,
        ),
        children: [
          _HeroCard(title: _cleanTitle, isSmall: isSmall),
          const SizedBox(height: 18),
          _SectionCard(
            title:
                'Ingredients (${_inventoryIngredients.length + _missingIngredients.length})',
            icon: Icons.restaurant_menu_rounded,
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                _IngredientGroupTitle(
                  title: 'Inventory Ingredients',
                  count: _inventoryIngredients.length,
                  color: const Color(0xFF10B981),
                ),
                const SizedBox(height: 10),
                if (_inventoryIngredients.isEmpty)
                  const _EmptyMiniCard(text: 'No inventory ingredient listed.'),
                ..._inventoryIngredients.map((ingredient) {
                  return _IngredientRow(
                    name: ingredient,
                    isNearExpiry: _isNearExpiry(ingredient),
                    isMissing: false,
                  );
                }),
                if (_missingIngredients.isNotEmpty) ...[
                  const SizedBox(height: 12),
                  _IngredientGroupTitle(
                    title: 'Missing / Restock Ingredients',
                    count: _missingIngredients.length,
                    color: const Color(0xFFF59E0B),
                  ),
                  const SizedBox(height: 10),
                  ..._missingIngredients.map((ingredient) {
                    return _IngredientRow(
                      name: ingredient,
                      isNearExpiry: false,
                      isMissing: true,
                    );
                  }),
                ],
              ],
            ),
          ),
          const SizedBox(height: 18),
          _SectionCard(
            title: 'Cooking Steps',
            icon: Icons.list_alt_rounded,
            child: Column(
              children: List.generate(_cleanSteps.length, (index) {
                return _StepRow(number: index + 1, text: _cleanSteps[index]);
              }),
            ),
          ),
          const SizedBox(height: 18),
          _WhyCard(text: widget.whyRecommended),
        ],
      ),
      bottomNavigationBar: _CookNowBottomBar(
        isCooking: _isCooking,
        onPressed: _handleCookNow,
      ),
    );
  }
}

